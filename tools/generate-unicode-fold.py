"""Generate matching Unicode case-fold tables for Go and LuCI (no dependencies)."""
import json
from pathlib import Path
import unicodedata

root = Path(__file__).resolve().parent.parent
# Single-rune lowercase is handled by the runtimes. Include full folds and
# multi-rune lowercase, e.g. German sharp S, Greek final sigma and dotted I.
folds = {chr(n): chr(n).casefold() for n in range(0x110000)
         if chr(n).casefold() != chr(n).lower() or len(chr(n).casefold()) > 1}
header = f"Generated by tools/generate-unicode-fold.py, Unicode {unicodedata.unidata_version}."
go = [f"// {header}", "package textutil", "", 'import ("strings"; "unicode"; "golang.org/x/text/unicode/norm")', "",
      "var fullFolds = map[rune]string{"]
for char, folded in folds.items():
    go.append(f"0x{ord(char):x}: {json.dumps(folded, ensure_ascii=True)},")
go.extend(["}", "", "// Fold compares user text independently of case and Unicode composition.",
           "func Fold(value string) string {", "var result strings.Builder", "result.Grow(len(value))",
           "for _, r := range norm.NFC.String(strings.TrimSpace(value)) {",
           "if folded, ok := fullFolds[r]; ok { result.WriteString(folded) } else { result.WriteRune(unicode.ToLower(r)) }",
           "}", "return norm.NFC.String(result.String())", "}", ""])
target = root / "internal/textutil"
target.mkdir(exist_ok=True)
(target / "fold.go").write_text("\n".join(go), encoding="utf-8", newline="\n")
js = f"""'use strict';
'require baseclass';

// {header}
var fullFolds = {json.dumps(folds, ensure_ascii=True, separators=(',', ':'))};
function normalize(value) {{ return String(value == null ? '' : value).trim().normalize('NFC'); }}
function fold(value) {{
 return Array.from(normalize(value), function(ch) {{ return fullFolds[ch] || ch.toLowerCase(); }}).join('').normalize('NFC');
}}
function cut(value, length) {{ return Array.from(normalize(value)).slice(0,length).join(''); }}
return baseclass.extend({{normalize:normalize, fold:fold, cut:cut}});
"""
(root / "htdocs/luci-static/resources/view/resproxy/unicode_text.js").write_text(js, encoding="utf-8", newline="\n")
